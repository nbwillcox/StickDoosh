#!/usr/bin/env python3
"""Scan assets/music, assets/sfx, assets/vo and write js/audiolist.js (SGS.AUDIO_FILES).

Re-run any time audio files are added/changed:   python tools/make_audiolist.py
Plain python 3, stdlib only.  VO curse ranges + text hashes come from tools/tts/vo_manifest.json.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTS = ('.mp3', '.ogg', '.wav', '.m4a')


def scan_flat(sub):
    d = os.path.join(ROOT, 'assets', sub)
    out = {}
    if os.path.isdir(d):
        for f in sorted(os.listdir(d)):
            stem, ext = os.path.splitext(f)
            if ext.lower() in EXTS and not f.startswith('_'):
                # prefer mp3 if several formats exist
                if stem not in out or ext.lower() == '.mp3':
                    out[stem] = 'assets/%s/%s' % (sub, f)
    return out


def scan_vo():
    d = os.path.join(ROOT, 'assets', 'vo')
    man = {}
    mp = os.path.join(ROOT, 'tools', 'tts', 'vo_manifest.json')
    if os.path.isfile(mp):
        with open(mp, 'r', encoding='utf-8') as fh:
            man = json.load(fh)
    out = {}
    if os.path.isdir(d):
        for sp in sorted(os.listdir(d)):
            sd = os.path.join(d, sp)
            if not os.path.isdir(sd):
                continue
            for f in sorted(os.listdir(sd)):
                stem, ext = os.path.splitext(f)
                if ext.lower() not in EXTS:
                    continue
                lid = '%s/%s' % (sp, stem)
                m = man.get(lid, {})
                ent = {'src': 'assets/vo/%s/%s' % (sp, f), 'curses': m.get('curses', [])}
                if m.get('h'):
                    ent['h'] = m['h']
                if m.get('d'):
                    ent['d'] = m['d']
                out[lid] = ent
    return out


def main():
    music = scan_flat('music')
    sfx = scan_flat('sfx')
    vo = scan_vo()
    j = lambda o: json.dumps(o, separators=(',', ':'), sort_keys=True)
    lines = [
        '/* GENERATED by tools/make_audiolist.py - do not edit. Re-run after adding audio files. */',
        'window.SGS=window.SGS||{};',
        'window.SGS.AUDIO_FILES={',
        'music:' + j(music) + ',',
        'sfx:' + j(sfx) + ',',
        'vo:' + j(vo),
        '};',
        ''
    ]
    with open(os.path.join(ROOT, 'js', 'audiolist.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines))
    print('audiolist.js: %d music, %d sfx, %d vo' % (len(music), len(sfx), len(vo)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
